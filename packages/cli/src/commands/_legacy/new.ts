interface NewOptions {
  workflow?: string;
  fromExisting?: boolean;
  template?: string;
  description?: string;
}

/* YAML serialization is handled by yaml.stringify in STATUS_TEMPLATE */

/**
 * Validate workflow type
 */
function validateWorkflowType(workflow: string): WorkflowType {
  if (!VALID_WORKFLOWS.includes(workflow as WorkflowType)) {
    console.error(
      `Error: Invalid workflow type '${workflow}'. Valid options: ${VALID_WORKFLOWS.join(", ")}`
    );
    throw new CLIError(
      `Invalid workflow type '${workflow}'. Valid options: ${VALID_WORKFLOWS.join(", ")}`,
      1
    );
  }
  return workflow as WorkflowType;
}

/**
 * Validate feature name
 * - Only lowercase letters, numbers, and hyphens
 * - Max 64 characters
 * - Cannot start or end with hyphen
 * - No consecutive hyphens
 * - Not a reserved word
 * - No path traversal characters
 */
function validateFeatureName(name: string): { valid: boolean; error?: string } {
  // Check for path traversal (security)
  try {
    validatePathComponent(name);
  } catch (err) {
    return {
      valid: false,
      error: err instanceof Error ? err.message : "Invalid feature name",
    };
  }

  // Check reserved words
  if (RESERVED_WORDS.includes(name.toLowerCase())) {
    return {
      valid: false,
      error: `'${name}' is a reserved word and cannot be used as a feature name`,
    };
  }

  // Check length
  if (name.length === 0) {
    return { valid: false, error: "Feature name cannot be empty" };
  }

  if (name.length > 64) {
    return {
      valid: false,
      error: "Feature name cannot exceed 64 characters",
    };
  }

  // Check format: only lowercase letters, numbers, hyphens
  if (!/^[a-z0-9-]+$/.test(name)) {
    return {
      valid: false,
      error: "Feature name must contain only lowercase letters, numbers, and hyphens (kebab-case)",
    };
  }

  // Check start/end characters
  if (name.startsWith("-") || name.endsWith("-")) {
    return {
      valid: false,
      error: "Feature name cannot start or end with a hyphen",
    };
  }

  // Check consecutive hyphens
  if (name.includes("--")) {
    return {
      valid: false,
      error: "Feature name cannot contain consecutive hyphens",
    };
  }

  return { valid: true };
}

export function createNewCommand(): Command {
  const cmd = new Command("new")
    .description("Create new feature")
    .argument("<name>", "Feature name (kebab-case)")
    .option("-w, --workflow <type>", "Workflow to use", "simple")
    .option("--from-existing", "Start from existing documents (Brownfield)")
    .option("-t, --template <name>", "Template to use")
    .option("-d, --description <text>", "Feature description")
    .action(async (name: string, options: NewOptions) => {
      await runNew(name, options);
    });

  return cmd;
}

async function runNew(name: string, options: NewOptions): Promise<void> {
  const cwd = process.cwd();
  const oboraDir = join(cwd, ".obora");
  const featuresDir = join(oboraDir, "features");
  const featureDir = join(featuresDir, name);
  const archiveDir = join(oboraDir, "archive");

  // Check if .obora/ exists
  if (!existsSync(oboraDir)) {
    console.error("Error: Not in an obora project. Run 'obora init' first.");
    throw new CLIError("Not in an obora project. Run 'obora init' first.", 3);
  }

  // Validate feature name
  const validation = validateFeatureName(name);
  if (!validation.valid) {
    console.error(`Error: ${validation.error}`);
    throw new CLIError(validation.error || "Invalid feature name", 1);
  }

  // Check for duplicate feature
  if (existsSync(featureDir)) {
    console.error(`Error: Feature '${name}' already exists.`);
    throw new CLIError(`Feature '${name}' already exists.`, 1);
  }

  // Warn if archived feature with same name exists
  const archivedFeature = join(archiveDir, name);
  if (existsSync(archivedFeature)) {
    console.warn(
      `Warning: An archived feature with name '${name}' exists. Consider using a different name.`
    );
  }

  const now = new Date().toISOString().split("T")[0]; // YYYY-MM-DD
  const description = options.description?.trim() || "";
  // Validate and use workflow type
  const workflow = validateWorkflowType(options.workflow || "simple");

  console.log(`Creating feature: ${name}`);

  // Create directory structure
  await fs.ensureDir(featureDir);
  await fs.ensureDir(join(featureDir, "context"));

  // Create files
  const proposal = description
    ? `${PROPOSAL_TEMPLATE(name, now)}\n## 한 줄 설명\n\n${description}\n`
    : PROPOSAL_TEMPLATE(name, now);
  await fs.writeFile(join(featureDir, "proposal.md"), proposal, "utf-8");
  console.log(`  Created: .obora/features/${name}/proposal.md`);

  await fs.writeFile(join(featureDir, "design.md"), DESIGN_TEMPLATE(name, now), "utf-8");
  console.log(`  Created: .obora/features/${name}/design.md`);

  await fs.writeFile(join(featureDir, "tasks.md"), TASKS_TEMPLATE(name, now), "utf-8");
  console.log(`  Created: .obora/features/${name}/tasks.md`);

  await fs.writeFile(
    join(featureDir, "status.yaml"),
    STATUS_TEMPLATE(name, now, workflow, description),
    "utf-8"
  );
  console.log(`  Created: .obora/features/${name}/status.yaml`);

  await fs.writeFile(join(featureDir, "context", ".gitkeep"), "", "utf-8");
  console.log(`  Created: .obora/features/${name}/context/`);

  await fs.writeFile(
    join(featureDir, "context", "README.md"),
    CONTEXT_README_TEMPLATE(name),
    "utf-8"
  );
  console.log(`  Created: .obora/features/${name}/context/README.md`);

  if (options.fromExisting) {
    console.log("");
    console.log("Note: --from-existing mode enabled.");
    console.log("  → Edit proposal.md to import your existing documentation");
  }

  console.log("");
  console.log(`✓ Feature '${name}' created successfully!`);
  console.log("");
  console.log("Next steps:");
  console.log(`  1. Edit .obora/features/${name}/proposal.md to define requirements`);
  console.log(`  2. Run 'obora plan ${name}' to generate implementation plan`);
  console.log(`  3. Run 'obora run ${name}' to start development`);
}

export { runNew, validateFeatureName };
