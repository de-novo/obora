const STATUS_TEMPLATE = (
  name: string,
  date: string,
  workflow: string,
  description: string
) => {
  const status = {
    feature: {
      name,
      description,
      created_at: date,
      workflow,
    },
    status: "pending", // pending | running | completed | failed | blocked | paused | cancelled
    progress: {
      current_stage: "planning",
      completed_stages: [] as string[],
    },
    metadata: {
      last_updated: date,
      notes: "",
    },
  };

  return `# Status file for feature: ${name}\n# Generated by: obora new\n\n${yaml.stringify(status)}`;
};

